// Turns the token sets into the package's outputs: dist/tokens.css (roles as custom properties, light
// and dark paired with light-dark()), dist/theme.css (the same roles as a Tailwind v4 @theme) and
// dist/tokens.js with its .d.ts (typed values for code, charts and MCP Apps). Only roles, accents and
// geometry leave the package; the raw palette stays private (hub ui-standard §2).

import { TokenSet, cssDimension, cssFontFamily, readTokens } from "./dtcg.ts";

export type Mode = "light" | "dark";
export const MODES: Mode[] = ["light", "dark"];

// The default product: [data-product] unset means Forspring's blue.
export const DEFAULT_PRODUCT = "forspring";

// Roles that follow the product. Everything else is the same in every product.
const PRODUCT_ROLES = ["primary", "primary-foreground", "ring"] as const;

const HEADER = "Generated by scripts/build.ts from tokens/*.json (W3C DTCG 2025.10). Do not edit; change the tokens and run pnpm build.";

export type Model = {
  roles: string[];
  products: string[];
  // role -> mode -> #rrggbb, with primary and ring at the default product
  colors: Record<string, Record<Mode, string>>;
  // product -> role (primary, primary-foreground, ring) -> mode -> #rrggbb
  product: Record<string, Record<(typeof PRODUCT_ROLES)[number], Record<Mode, string>>>;
  radius: Record<string, number>;
  space: Record<string, number>;
  text: Record<string, Record<string, number>>;
  fonts: Record<string, string>;
};

export function model(dir: string): Model {
  const { shared, themes } = readTokens(dir);
  const sets = { light: new TokenSet([...shared, themes.light]), dark: new TokenSet([...shared, themes.dark]) };
  const problems = [...new Set([...sets.light.problems, ...sets.dark.problems])];
  const light = sets.light.names("role");
  const dark = sets.dark.names("role");
  for (const r of light) if (!dark.includes(r)) problems.push(`role.${r} is in role.light.json but not role.dark.json`);
  for (const r of dark) if (!light.includes(r)) problems.push(`role.${r} is in role.dark.json but not role.light.json`);
  if (problems.length) throw new TokenProblems(problems);

  const s = sets.light;
  const colors: Model["colors"] = {};
  for (const r of light) colors[r] = { light: sets.light.color(`role.${r}`), dark: sets.dark.color(`role.${r}`) };

  const products = s.names("accent");
  if (!products.includes(DEFAULT_PRODUCT)) throw new TokenProblems([`accent.${DEFAULT_PRODUCT} is missing`]);
  const product: Model["product"] = {};
  for (const p of products) {
    const accent = { light: s.color(`accent.${p}.light`), dark: s.color(`accent.${p}.dark`) };
    // primary-foreground is the same in every product today (white on light, the ground on dark);
    // it sits here so a future accent too pale for white text can carry its own.
    product[p] = { primary: accent, "primary-foreground": colors["primary-foreground"]!, ring: accent };
  }

  const px = (path: string) => {
    const d = s.dimension(path);
    if (d.unit !== "px") throw new TokenProblems([`${path}: geometry is written in px`]);
    return d.value;
  };
  const record = (group: string) => Object.fromEntries(s.names(group).map((n) => [n, px(`${group}.${n}`)]));
  return {
    roles: light,
    products,
    colors,
    product,
    radius: record("radius"),
    space: record("space"),
    text: Object.fromEntries(s.names("text").map((ladder) => [ladder, record(`text.${ladder}`)])),
    fonts: Object.fromEntries(s.names("font").map((n) => [n, cssFontFamily(s.fontFamily(`font.${n}`))])),
  };
}

export class TokenProblems extends Error {
  readonly problems: string[];
  constructor(problems: string[]) {
    super(`tokens are not valid:\n  ${problems.join("\n  ")}`);
    this.problems = problems;
  }
}

const pair = (c: Record<Mode, string>) => (c.light === c.dark ? c.light : `light-dark(${c.light}, ${c.dark})`);

function geometry(m: Model): string[] {
  return [
    ...Object.entries(m.radius).map(([k, v]) => `--radius-${k}: ${v}px;`),
    ...Object.entries(m.space).map(([k, v]) => `--space-${k}: ${v}px;`),
    ...Object.entries(m.text).flatMap(([ladder, steps]) => Object.entries(steps).map(([k, v]) => `--text-${ladder}-${k}: ${v}px;`)),
    ...Object.entries(m.fonts).map(([k, v]) => `--font-${k}: ${v};`),
  ];
}

const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;

export function tokensCss(m: Model): string {
  const root = [
    // light-dark() picks by the used color-scheme of the element where a role is finally used, so
    // the explicit overrides below only have to set color-scheme and every role follows.
    "color-scheme: light dark;",
    ...m.roles.map((r) => `--${r}: ${pair(m.colors[r]!)};`),
    ...geometry(m),
  ];
  return [
    `/* ${HEADER} */\n`,
    block(":root", root),
    "/* An explicit theme (the person's choice, or an MCP host's) wins over the system setting. */",
    block('[data-theme="light"]', ["color-scheme: light;"]),
    block('[data-theme="dark"]', ["color-scheme: dark;"]),
    "/* One accent per product (hub D-90). Unset means Forspring. */",
    ...m.products.map((p) => block(`[data-product="${p}"]`, PRODUCT_ROLES.map((r) => `--${r}: ${pair(m.product[p]![r])};`))),
  ].join("\n");
}

export function themeCss(m: Model): string {
  // Geometry and fonts carry literal values, not var(): Tailwind's namespaces (--radius-*, --font-*,
  // --text-*) use the same names as tokens.css, and `--font-sans: var(--font-sans)` would refer to
  // itself. The values are the same tokens, so the two files cannot disagree.
  const lines = [
    ...m.roles.map((r) => `--color-${r}: var(--${r});`),
    ...Object.entries(m.radius).map(([k, v]) => `--radius-${k}: ${v}px;`),
    `--spacing: ${m.space["1"]}px;`,
    ...Object.entries(m.text).flatMap(([ladder, steps]) => Object.entries(steps).map(([k, v]) => `--text-${ladder}-${k}: ${v}px;`)),
    ...Object.entries(m.fonts).map(([k, v]) => `--font-${k}: ${v};`),
  ];
  return [
    `/* ${HEADER} */\n`,
    `/* Use after Tailwind: @import "tailwindcss"; @import "@forspring/ui/theme.css"; */`,
    `@import "./tokens.css";\n`,
    "/* dark: follows the system unless data-theme says otherwise, the same rule tokens.css applies. */",
    `@custom-variant dark {
  @media (prefers-color-scheme: dark) {
    &:where(:not([data-theme="light"], [data-theme="light"] *)) {
      @slot;
    }
  }
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
}
`,
    "@theme inline " + block("", lines).trimStart(),
  ].join("\n");
}

function roleColors(m: Model, mode: Mode) {
  return Object.fromEntries(m.roles.map((r) => [r, m.colors[r]![mode]]));
}

function values(m: Model) {
  return {
    products: m.products,
    accents: Object.fromEntries(m.products.map((p) => [p, m.product[p]!.primary])),
    roles: { light: roleColors(m, "light"), dark: roleColors(m, "dark") },
    chart: {
      light: m.roles.filter((r) => r.startsWith("chart-")).map((r) => m.colors[r]!.light),
      dark: m.roles.filter((r) => r.startsWith("chart-")).map((r) => m.colors[r]!.dark),
    },
    radius: m.radius,
    space: m.space,
    text: m.text,
    fonts: m.fonts,
  };
}

export function tokensJs(m: Model): string {
  const v = values(m);
  const out = [`// ${HEADER}\n`];
  for (const [k, val] of Object.entries(v)) out.push(`export const ${k} = Object.freeze(${JSON.stringify(val, null, 2)});\n`);
  out.push(`// The roles for one product in one theme: the shared roles with that product's accent.
export function themeFor(product, mode) {
  const accent = accents[product];
  if (!accent) throw new Error(\`unknown product: \${product}\`);
  return { ...roles[mode], primary: accent[mode], ring: accent[mode] };
}
`);
  return out.join("\n");
}

export function tokensDts(m: Model): string {
  const v = values(m);
  const union = (xs: string[]) => xs.map((x) => JSON.stringify(x)).join(" | ");
  return `// ${HEADER}

export type Product = ${union(m.products)};
export type Mode = "light" | "dark";
export type Role = ${union(m.roles)};

type Deep<T> = { readonly [K in keyof T]: Deep<T[K]> };

/** Every product key, the values [data-product] takes. */
export declare const products: Deep<${JSON.stringify(v.products)}>;
/** Each product's accent (hub D-90), at least 4.5:1 on background in its theme. */
export declare const accents: Deep<${JSON.stringify(v.accents)}>;
/** Semantic roles per theme, #rrggbb; primary and ring are Forspring's. Use themeFor for another product. */
export declare const roles: Deep<${JSON.stringify(v.roles)}>;
/** Categorical series colours in their fixed order, per theme. Identity only; never cycled. */
export declare const chart: Deep<${JSON.stringify(v.chart)}>;
/** Radii in px. */
export declare const radius: Deep<${JSON.stringify(v.radius)}>;
/** Spacing in px; the key is the multiple of 4px. */
export declare const space: Deep<${JSON.stringify(v.space)}>;
/** Font sizes in px: chrome (dense UI) and content (pages). */
export declare const text: Deep<${JSON.stringify(v.text)}>;
/** CSS font-family stacks. */
export declare const fonts: Deep<${JSON.stringify(v.fonts)}>;
/** The roles for one product in one theme. */
export declare function themeFor(product: Product, mode: Mode): { readonly [R in Role]: string };
`;
}

export function build(dir: string): Record<string, string> {
  const m = model(dir);
  return {
    "tokens.css": tokensCss(m),
    "theme.css": themeCss(m),
    "tokens.js": tokensJs(m),
    "tokens.d.ts": tokensDts(m),
  };
}
