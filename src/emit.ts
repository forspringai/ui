// Turns the token sets into the package's outputs: dist/tokens.css (roles as custom properties, light
// and dark paired with light-dark()), dist/theme.css (the same roles as a Tailwind v4 @theme) and
// dist/tokens.js with its .d.ts (typed values for code, charts and MCP Apps). Only roles, accents,
// geometry, motion and shadows leave the package; the raw palette stays private (hub ui-standard §2).

import { mix } from "./color.ts";
import { type ShadowLayer, TokenSet, cssColor, cssCubicBezier, cssDimension, cssDuration, cssFontFamily, readTokens } from "./dtcg.ts";

export type Mode = "light" | "dark";
export const MODES: Mode[] = ["light", "dark"];

// The default product: [data-product] unset means Forspring's blue.
export const DEFAULT_PRODUCT = "forspring";

// Roles that follow the product. Everything else is the same in every product. mark is the doll's
// colour (hub D-101): the accent in a product, ink (the mark role) on Forspring's own pages.
const PRODUCT_ROLES = ["primary", "primary-foreground", "ring", "mark"] as const;

const HEADER = "Generated by scripts/build.ts from tokens/*.json (W3C DTCG 2025.10). Do not edit; change the tokens and run pnpm build.";

export type Model = {
  roles: string[];
  products: string[];
  // role -> mode -> #rrggbb, with primary and ring at the default product
  colors: Record<string, Record<Mode, string>>;
  // product -> role (primary, primary-foreground, ring, mark) -> mode -> #rrggbb
  product: Record<string, Record<(typeof PRODUCT_ROLES)[number], Record<Mode, string>>>;
  radius: Record<string, number>;
  space: Record<string, number>;
  // control heights (D-14): steps of the space scale, so a row of controls shares one height
  control: Record<string, number>;
  text: Record<string, Record<string, number>>;
  // line-height per ladder step (D-27), unitless, plus solid (1) for one line in its own box
  leading: { solid: number } & Record<string, Record<string, number>>;
  // viewport widths in px; media queries cannot read custom properties, so these go to TS and Tailwind
  breakpoint: Record<string, number>;
  // durations in seconds, easings as cubic-bezier() (D-27)
  motion: { duration: Record<string, number>; ease: Record<string, [number, number, number, number]> };
  // elevation -> mode -> a box-shadow value; the geometry is the same in both modes
  shadow: Record<string, Record<Mode, string>>;
  fonts: Record<string, string>;
};

export function model(dir: string): Model {
  const { shared, themes } = readTokens(dir);
  const sets = { light: new TokenSet([...shared, themes.light]), dark: new TokenSet([...shared, themes.dark]) };
  const problems = [...new Set([...sets.light.problems, ...sets.dark.problems])];
  const light = sets.light.names("role");
  const dark = sets.dark.names("role");
  for (const r of light) if (!dark.includes(r)) problems.push(`role.${r} is in role.light.json but not role.dark.json`);
  for (const r of dark) if (!light.includes(r)) problems.push(`role.${r} is in role.dark.json but not role.light.json`);
  if (problems.length) throw new TokenProblems(problems);

  const s = sets.light;
  const colors: Model["colors"] = {};
  for (const r of light) colors[r] = { light: sets.light.color(`role.${r}`), dark: sets.dark.color(`role.${r}`) };
  // Each chart slot's tint (D-37): the slot at chart.tint on the card, per theme, so an identity
  // surface (a calendar block, a timeline bar) is a named token, never a free color-mix.
  const share = sets.light.number("chart.tint");
  const roles = [...light];
  for (const r of light.filter((n) => /^chart-\d+$/.test(n))) {
    colors[`${r}-tint`] = { light: mix(colors[r]!.light, colors.card!.light, share), dark: mix(colors[r]!.dark, colors.card!.dark, share) };
    roles.push(`${r}-tint`);
  }

  const products = s.names("accent");
  if (!products.includes(DEFAULT_PRODUCT)) throw new TokenProblems([`accent.${DEFAULT_PRODUCT} is missing`]);
  const product: Model["product"] = {};
  for (const p of products) {
    const accent = { light: s.color(`accent.${p}.light`), dark: s.color(`accent.${p}.dark`) };
    // primary-foreground is the same in every product today (white on light, the ground on dark);
    // it sits here so a future accent too pale for white text can carry its own.
    // Forspring is the colourless parent: its doll is ink; every product's doll is its accent (hub D-101).
    const mark = p === DEFAULT_PRODUCT ? colors.mark! : accent;
    product[p] = { primary: accent, "primary-foreground": colors["primary-foreground"]!, ring: accent, mark };
  }

  const px = (path: string) => {
    const d = s.dimension(path);
    if (d.unit !== "px") throw new TokenProblems([`${path}: geometry is written in px`]);
    return d.value;
  };
  const record = (group: string) => Object.fromEntries(s.names(group).map((n) => [n, px(`${group}.${n}`)]));
  const ladders = s.names("text");

  // Every ladder step has a leading and every leading a step, so a size never goes out without one.
  const leading: Record<string, number | Record<string, number>> = { solid: s.number("leading.solid") };
  const leadingProblems: string[] = [];
  for (const ladder of s.names("leading").filter((n) => n !== "solid")) {
    if (!ladders.includes(ladder)) leadingProblems.push(`leading.${ladder} has no text.${ladder}`);
  }
  for (const ladder of ladders) {
    const steps = s.names(`text.${ladder}`);
    const lead = s.names(`leading.${ladder}`);
    for (const n of steps) if (!lead.includes(n)) leadingProblems.push(`text.${ladder}.${n} has no leading.${ladder}.${n}`);
    for (const n of lead) if (!steps.includes(n)) leadingProblems.push(`leading.${ladder}.${n} has no text.${ladder}.${n}`);
    leading[ladder] = Object.fromEntries(lead.map((n) => [n, s.number(`leading.${ladder}.${n}`)]));
  }
  if (leadingProblems.length) throw new TokenProblems(leadingProblems);

  const seconds = (path: string) => Number(cssDuration(s.duration(path)).slice(0, -1));
  const shadow: Model["shadow"] = {};
  for (const level of s.names("shadow")) {
    const [l, d] = [s.shadow(`shadow.${level}.light`), s.shadow(`shadow.${level}.dark`)];
    const geometry = (layers: ShadowLayer[]) => JSON.stringify(layers.map(({ color: _, ...rest }) => rest));
    if (geometry(l) !== geometry(d)) throw new TokenProblems([`shadow.${level}: light and dark differ in more than colour, which light-dark() cannot pair`]);
    shadow[level] = { light: cssShadow(l), dark: cssShadow(d) };
  }

  return {
    roles,
    products,
    colors,
    product,
    radius: record("radius"),
    space: record("space"),
    control: record("control"),
    text: Object.fromEntries(ladders.map((ladder) => [ladder, record(`text.${ladder}`)])),
    leading: leading as Model["leading"],
    breakpoint: record("breakpoint"),
    motion: {
      duration: Object.fromEntries(s.names("motion.duration").map((n) => [n, seconds(`motion.duration.${n}`)])),
      ease: Object.fromEntries(s.names("motion.ease").map((n) => [n, s.cubicBezier(`motion.ease.${n}`)])),
    },
    shadow,
    fonts: Object.fromEntries(s.names("font").map((n) => [n, cssFontFamily(s.fontFamily(`font.${n}`))])),
  };
}

export class TokenProblems extends Error {
  readonly problems: string[];
  constructor(problems: string[]) {
    super(`tokens are not valid:\n  ${problems.join("\n  ")}`);
    this.problems = problems;
  }
}

const pair = (c: Record<Mode, string>) => (c.light === c.dark ? c.light : `light-dark(${c.light}, ${c.dark})`);

const cssShadow = (layers: ShadowLayer[]) =>
  layers.map((l) => [l.inset ? "inset" : "", ...[l.offsetX, l.offsetY, l.blur, l.spread].map(cssDimension), cssColor(l.color)].filter(Boolean).join(" ")).join(", ");

// light-dark() takes colours only, so a shadow pairs its colours and keeps the shared geometry outside.
// A shadow value's colour is its last word (cssShadow writes it there).
function pairShadow(s: Record<Mode, string>): string {
  if (s.light === s.dark) return s.light;
  const split = (v: string) => /^(.*?) (#[0-9a-f]{6}|rgb\([^)]*\))$/.exec(v)!;
  const [l, d] = [split(s.light), split(s.dark)];
  return `${l[1]} light-dark(${l[2]}, ${d[2]})`;
}

const ladderSteps = (m: Model) =>
  Object.entries(m.leading).flatMap(([ladder, steps]) => (typeof steps === "number" ? [] : Object.entries(steps).map(([k, v]) => [ladder, k, v] as const)));

function geometry(m: Model): string[] {
  return [
    ...Object.entries(m.radius).map(([k, v]) => `--radius-${k}: ${v}px;`),
    ...Object.entries(m.space).map(([k, v]) => `--space-${k}: ${v}px;`),
    ...Object.entries(m.control).map(([k, v]) => `--control-${k}: ${v}px;`),
    ...Object.entries(m.text).flatMap(([ladder, steps]) => Object.entries(steps).map(([k, v]) => `--text-${ladder}-${k}: ${v}px;`)),
    `--leading-solid: ${m.leading.solid};`,
    ...ladderSteps(m).map(([ladder, k, v]) => `--leading-${ladder}-${k}: ${v};`),
    ...Object.entries(m.fonts).map(([k, v]) => `--font-${k}: ${v};`),
    ...Object.entries(m.motion.duration).map(([k, v]) => `--motion-duration-${k}: ${v}s;`),
    ...Object.entries(m.motion.ease).map(([k, v]) => `--motion-ease-${k}: ${cssCubicBezier(v)};`),
    ...Object.entries(m.shadow).map(([k, v]) => `--shadow-${k}: ${pairShadow(v)};`),
  ];
}

const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;

export function tokensCss(m: Model): string {
  const root = [
    // light-dark() picks by the used color-scheme of the element where a role is finally used, so
    // the explicit overrides below only have to set color-scheme and every role follows.
    "color-scheme: light dark;",
    ...m.roles.map((r) => `--${r}: ${pair(m.colors[r]!)};`),
    ...geometry(m),
  ];
  return [
    `/* ${HEADER} */\n`,
    block(":root", root),
    "/* An explicit theme (the person's choice, or an MCP host's) wins over the system setting. */",
    block('[data-theme="light"]', ["color-scheme: light;"]),
    block('[data-theme="dark"]', ["color-scheme: dark;"]),
    "/* Under reduced motion every duration is 0 (D-27): what is built on the tokens stops moving. */",
    `@media (prefers-reduced-motion: reduce) {\n${block("  :root", Object.keys(m.motion.duration).map((k) => `  --motion-duration-${k}: 0s;`)).replace(/\n}\n$/, "\n  }\n")}}\n`,
    "/* One accent per product (hub D-90). Unset means Forspring. */",
    ...m.products.map((p) => block(`[data-product="${p}"]`, PRODUCT_ROLES.map((r) => `--${r}: ${pair(m.product[p]![r])};`))),
  ].join("\n");
}

export function themeCss(m: Model): string {
  // Geometry and fonts carry literal values, not var(): Tailwind's namespaces (--radius-*, --font-*,
  // --text-*) use the same names as tokens.css, and `--font-sans: var(--font-sans)` would refer to
  // itself. The values are the same tokens, so the two files cannot disagree.
  const lines = [
    ...m.roles.map((r) => `--color-${r}: var(--${r});`),
    ...Object.entries(m.radius).map(([k, v]) => `--radius-${k}: ${v}px;`),
    `--spacing: ${m.space["1"]}px;`,
    // h-control, h-control-small, min-h-control-touch: the same heights as components.css.
    ...Object.entries(m.control).map(([k, v]) => `--spacing-${["control", k.replace(/^height-?/, "")].filter(Boolean).join("-")}: ${v}px;`),
    // text-content-body sets its line-height too (Tailwind's --text-*--line-height companion), and
    // leading-content-body names it alone.
    ...Object.entries(m.text).flatMap(([ladder, steps]) =>
      Object.entries(steps).flatMap(([k, v]) => [`--text-${ladder}-${k}: ${v}px;`, `--text-${ladder}-${k}--line-height: ${(m.leading[ladder] as Record<string, number>)[k]};`]),
    ),
    `--leading-solid: ${m.leading.solid};`,
    ...ladderSteps(m).map(([ladder, k, v]) => `--leading-${ladder}-${k}: ${v};`),
    // phone:, tablet:, wide: are min-width, as Tailwind's own; max-phone: is "on a phone", the
    // max-width the components use.
    ...Object.entries(m.breakpoint).map(([k, v]) => `--breakpoint-${k}: ${v}px;`),
    ...Object.entries(m.fonts).map(([k, v]) => `--font-${k}: ${v};`),
    // ease-standard and ease-out; ease-out replaces Tailwind's own with the brand's curve.
    ...Object.entries(m.motion.ease).map(([k, v]) => `--ease-${k}: ${cssCubicBezier(v)};`),
    `--default-transition-duration: ${m.motion.duration.fast}s;`,
    `--default-transition-timing-function: ${cssCubicBezier(m.motion.ease.standard!)};`,
    ...Object.entries(m.shadow).map(([k, v]) => `--shadow-${k}: ${pairShadow(v)};`),
  ];
  return [
    `/* ${HEADER} */\n`,
    `/* Use after Tailwind: @import "tailwindcss"; @import "@forspring/ui/theme.css"; */`,
    `@import "./tokens.css";\n`,
    "/* dark: follows the system unless data-theme says otherwise, the same rule tokens.css applies. */",
    `@custom-variant dark {
  @media (prefers-color-scheme: dark) {
    &:where(:not([data-theme="light"], [data-theme="light"] *)) {
      @slot;
    }
  }
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
}
`,
    "@theme inline " + block("", lines).trimStart(),
  ].join("\n");
}

function roleColors(m: Model, mode: Mode) {
  return Object.fromEntries(m.roles.map((r) => [r, m.colors[r]![mode]]));
}

function values(m: Model) {
  return {
    products: m.products,
    accents: Object.fromEntries(m.products.map((p) => [p, m.product[p]!.primary])),
    marks: Object.fromEntries(m.products.map((p) => [p, m.product[p]!.mark])),
    roles: { light: roleColors(m, "light"), dark: roleColors(m, "dark") },
    chart: {
      light: m.roles.filter((r) => /^chart-\d+$/.test(r)).map((r) => m.colors[r]!.light),
      dark: m.roles.filter((r) => /^chart-\d+$/.test(r)).map((r) => m.colors[r]!.dark),
    },
    radius: m.radius,
    space: m.space,
    control: m.control,
    text: m.text,
    leading: m.leading,
    breakpoint: m.breakpoint,
    motion: m.motion,
    shadow: m.shadow,
    fonts: m.fonts,
  };
}

export function tokensJs(m: Model): string {
  const v = values(m);
  const out = [`// ${HEADER}\n`];
  for (const [k, val] of Object.entries(v)) out.push(`export const ${k} = Object.freeze(${JSON.stringify(val, null, 2)});\n`);
  out.push(`// The roles for one product in one theme: the shared roles with that product's accent.
export function themeFor(product, mode) {
  const accent = accents[product];
  if (!accent) throw new Error(\`unknown product: \${product}\`);
  return { ...roles[mode], primary: accent[mode], ring: accent[mode], mark: marks[product][mode] };
}
`);
  return out.join("\n");
}

export function tokensDts(m: Model): string {
  const v = values(m);
  const union = (xs: string[]) => xs.map((x) => JSON.stringify(x)).join(" | ");
  return `// ${HEADER}

export type Product = ${union(m.products)};
export type Mode = "light" | "dark";
export type Role = ${union(m.roles)};

type Deep<T> = { readonly [K in keyof T]: Deep<T[K]> };

/** Every product key, the values [data-product] takes. */
export declare const products: Deep<${JSON.stringify(v.products)}>;
/** Each product's accent (hub D-90), at least 4.5:1 on background in its theme. */
export declare const accents: Deep<${JSON.stringify(v.accents)}>;
/** Each product's doll colour (hub D-101): its accent, and ink (paper on dark) for Forspring. */
export declare const marks: Deep<${JSON.stringify(v.marks)}>;
/** Semantic roles per theme, #rrggbb; primary and ring are Forspring's. Use themeFor for another product. */
export declare const roles: Deep<${JSON.stringify(v.roles)}>;
/** Categorical series colours in their fixed order, per theme. Identity only; never cycled. */
export declare const chart: Deep<${JSON.stringify(v.chart)}>;
/** Radii in px. */
export declare const radius: Deep<${JSON.stringify(v.radius)}>;
/** Spacing in px; the key is the multiple of 4px. */
export declare const space: Deep<${JSON.stringify(v.space)}>;
/** Control heights in px (D-14): height (default), height-small, touch (the phone floor). */
export declare const control: Deep<${JSON.stringify(v.control)}>;
/** Font sizes in px: chrome (dense UI), content (pages) and marketing (landing pages, D-22). */
export declare const text: Deep<${JSON.stringify(v.text)}>;
/** Line-height per ladder step, unitless (D-27), and solid (1) for one line in a box of its own. */
export declare const leading: Deep<${JSON.stringify(v.leading)}>;
/** Viewport widths in px (D-27). Each is the widest the smaller layout goes: max-width: phone is "on a phone". */
export declare const breakpoint: Deep<${JSON.stringify(v.breakpoint)}>;
/** Durations in seconds and easings as cubic-bezier control points (D-27). Under reduced motion use 0. */
export declare const motion: Deep<${JSON.stringify(v.motion)}>;
/** box-shadow values per theme (D-27): raised for a thumb, overlay for what floats over the page. Never on a card. */
export declare const shadow: Deep<${JSON.stringify(v.shadow)}>;
/** CSS font-family stacks. */
export declare const fonts: Deep<${JSON.stringify(v.fonts)}>;
/** The roles for one product in one theme. */
export declare function themeFor(product: Product, mode: Mode): { readonly [R in Role]: string };
`;
}

export function build(dir: string): Record<string, string> {
  const m = model(dir);
  return {
    "tokens.css": tokensCss(m),
    "theme.css": themeCss(m),
    "tokens.js": tokensJs(m),
    "tokens.d.ts": tokensDts(m),
  };
}

// src/family.ts: the role values and product accents as a TypeScript module, for src/theme.ts.
// theme.ts runs in a Worker or a compiler, where the tokens cannot be read from disk, so the build
// writes the values it needs beside it; test/build.test.ts fails when the file is stale.
export function familyTs(m: Model): string {
  const union = (xs: string[]) => xs.map((x) => JSON.stringify(x)).join(" | ");
  const roles = { light: roleColors(m, "light"), dark: roleColors(m, "dark") };
  return `// ${HEADER}

export type Role = ${union(m.roles)};
export type Product = ${union(m.products)};
type Pair = { readonly light: string; readonly dark: string };

/** Every role's value per theme, #rrggbb; primary, ring and mark are Forspring's. */
export const ROLES: { readonly light: Readonly<Record<Role, string>>; readonly dark: Readonly<Record<Role, string>> } = ${JSON.stringify(roles, null, 2)};

/** Each product's own roles (primary, primary-foreground, ring, mark) per theme. */
export const PRODUCTS: Readonly<Record<Product, Readonly<Record<"primary" | "primary-foreground" | "ring" | "mark", Pair>>>> = ${JSON.stringify(m.product, null, 2)};
`;
}
