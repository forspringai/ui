// The outputs that are not built from the tokens: the font faces, the component stylesheets and the
// demo page. Like the token outputs they are committed in dist/ (D-2) and checked by
// test/build.test.ts against a fresh build.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { demoPage } from "../demo/index.ts";
import { fontFaces, googleFontFace } from "./html.ts";

const generated = (from: string) => `/* Generated by scripts/build.ts from ${from}. Do not edit; change the source and run pnpm build. */\n\n`;

export function assets(root: string): Record<string, string> {
  const css = (name: string) => generated(`css/${name}`) + readFileSync(join(root, "css", name), "utf8");
  return {
    // Relative to dist/: the package's fonts/ folder. A bundler (Vite, Astro) resolves these from
    // node_modules and emits the files; a product that inlines its CSS uses fontFaces("/its/path/").
    "fonts.css": generated("src/html.ts fontFaces()") + fontFaces("../fonts/"),
    "components.css": css("components.css"),
    "google-button.css": css("google-button.css") + "\n" + googleFontFace("../fonts/"),
    "demo/index.html": demoPage() + "\n",
  };
}
