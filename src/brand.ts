// The brand files (hub D-101), generated from the tokens so a colour lives in one place: per product,
// the doll alone (mark.svg, favicon.svg) and the lockup (logo.svg), each with its dark variant inside
// a prefers-color-scheme rule. scripts/build.ts writes them to dist/brand/<product>/ and brand/<product>/
// and renders the PNGs from them (scripts/brand-png.ts).
//
// The lockup's wordmark is outlined (brand/wordmarks.json, from scripts/wordmarks.py), so it renders
// with no font. Its proportions are the marketing size of the chosen sample: a 56px mark box, the name
// at 44px, 12px apart, the name's cap height centred on the box, as the bar centres them.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { Model, Mode } from "./emit.ts";
import { MARK_PATHS, MARK_VIEWBOX, PRODUCT_NAMES, type Product } from "./html.ts";

export type Wordmarks = {
  unitsPerEm: number;
  capHeight: number;
  names: Record<string, { d: string; width: number }>;
};

export const readWordmarks = (root: string): Wordmarks => JSON.parse(readFileSync(join(root, "brand", "wordmarks.json"), "utf8"));

// The doll's own extent inside the mark's viewBox (-184 -160 368 368): the head's circle is r 160
// about the origin, and the coil ends at y 151 with a 5-unit stroke.
const DOLL = { left: -160, right: 160, top: -160, bottom: 153.5 };
export const DOLL_HEIGHT = DOLL.bottom - DOLL.top;
/** Clear space around a lockup: a quarter of the doll's height (hub D-101). */
export const CLEAR = DOLL_HEIGHT / 4;
// favicon.svg is cropped to the doll, so a 16px icon is all doll.
const FAVICON_VIEWBOX = "-165 -168 330 330";

const r1 = (n: number) => Math.round(n * 10) / 10;
const GENERATED = "Generated by @forspring/ui scripts/build.ts from tokens/ (hub D-101). Do not edit.";

type Colours = Record<Mode, string>;

/** The doll's colour and the wordmark's (ink, paper on dark) for a product, from the tokens. */
export function brandColours(m: Model, p: Product): { mark: Colours; word: Colours } {
  const mark = m.product[p]?.mark;
  if (!mark) throw new Error(`no accent for ${p} in tokens/accent.json`);
  return { mark, word: m.colors.foreground! };
}

const style = (rules: Record<Mode, string>) => `<style>${rules.light}@media (prefers-color-scheme: dark){${rules.dark}}</style>`;
const dollRules = (c: Colours, mode: Mode) => `.fill{fill:${c[mode]}}.coil{stroke:${c[mode]}}`;

/** The doll alone: mark.svg (the mark's own box, with room around it) or favicon.svg (cropped to the doll). */
export function markSvg(m: Model, p: Product, crop = false): string {
  const { mark } = brandColours(m, p);
  const box = crop ? FAVICON_VIEWBOX : MARK_VIEWBOX;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}" width="${crop ? 32 : 368}" height="${crop ? 32 : 368}"><!-- ${GENERATED} --><title>${PRODUCT_NAMES[p]}</title>${style({ light: dollRules(mark, "light"), dark: dollRules(mark, "dark") })}${MARK_PATHS}</svg>\n`;
}

/** The lockup's layout in the mark's units, shared by logo.svg and the tests. */
export function lockup(w: Wordmarks, p: Product) {
  const name = w.names[PRODUCT_NAMES[p]];
  if (!name) throw new Error(`no outlined wordmark for ${PRODUCT_NAMES[p]}: run scripts/wordmarks.py`);
  const unit = 368 / 56; // mark units per px at the marketing size
  const scale = (44 * unit) / w.unitsPerEm;
  const x = 184 + 12 * unit; // after the mark box and the gap
  const baseline = 24 + (w.capHeight * scale) / 2; // 24 is the mark box's middle
  const ys = [...name.d.matchAll(/-?\d+(?:\.\d+)?\s(-?\d+(?:\.\d+)?)/g)].map((g) => Number(g[1]));
  const top = Math.min(DOLL.top, baseline + Math.min(...ys) * scale);
  const bottom = Math.max(DOLL.bottom, baseline + Math.max(...ys) * scale);
  const right = x + name.width * scale;
  const box = { x: DOLL.left - CLEAR, y: top - CLEAR, width: right - DOLL.left + 2 * CLEAR, height: bottom - top + 2 * CLEAR };
  return { name, scale, x, baseline, box };
}

/** Doll plus wordmark, the wordmark outlined, with the clear space as the margin. */
export function logoSvg(m: Model, w: Wordmarks, p: Product): string {
  const { mark, word } = brandColours(m, p);
  const l = lockup(w, p);
  const b = l.box;
  const height = 120;
  const width = Math.round((height * b.width) / b.height);
  const rules = (mode: Mode) => `${dollRules(mark, mode)}.word{fill:${word[mode]}}`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${r1(b.x)} ${r1(b.y)} ${r1(b.width)} ${r1(b.height)}" width="${width}" height="${height}"><!-- ${GENERATED} --><title>${PRODUCT_NAMES[p]}</title>${style({ light: rules("light"), dark: rules("dark") })}${MARK_PATHS}<path class="word" transform="translate(${r1(l.x)} ${r1(l.baseline)}) scale(${Math.round(l.scale * 1e5) / 1e5})" d="${l.name.d}"/></svg>\n`;
}

/** The PNGs rendered from the SVGs: file, source SVG, size, and whether it sits on paper. */
export const PNGS = [
  { file: "favicon-32.png", from: "favicon.svg", width: 32, height: 32, paper: false },
  { file: "favicon-16.png", from: "favicon.svg", width: 16, height: 16, paper: false },
  { file: "apple-touch-icon-180.png", from: "mark.svg", width: 180, height: 180, paper: true },
  { file: "icon-512.png", from: "mark.svg", width: 512, height: 512, paper: true },
  { file: "logo-1200x300.png", from: "logo.svg", width: 1200, height: 300, paper: false },
] as const;

/** brand/<product>/{mark,favicon,logo}.svg for every product in the tokens. */
export function brandSvgs(m: Model, w: Wordmarks): Record<string, string> {
  const out: Record<string, string> = {};
  for (const p of m.products as Product[]) {
    out[`brand/${p}/mark.svg`] = markSvg(m, p);
    out[`brand/${p}/favicon.svg`] = markSvg(m, p, true);
    out[`brand/${p}/logo.svg`] = logoSvg(m, w, p);
  }
  return out;
}
